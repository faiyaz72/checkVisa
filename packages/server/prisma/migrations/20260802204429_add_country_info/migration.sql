SELECT DISTINCT code, NULL
FROM (
  SELECT "originCountryCode" AS code FROM "VisaRequirement"
  UNION
  SELECT "destinationCountryCode" AS code FROM "VisaRequirement"
) AS codes
ON CONFLICT ("countryCd") DO NOTHING;

